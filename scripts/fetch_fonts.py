"""Download the latin woff2 subsets for the site's three typefaces.

Google's CSS2 endpoint returns one @font-face block per unicode-range subset,
each preceded by a ``/* latin */`` style comment. We only ship the latin
subset: the UI copy is English and every other subset is dead weight on a
cold load.

Inter and JetBrains Mono are served as variable fonts, so every requested
weight resolves to the identical file. Collapsing those to a single
``font-weight: 300 600`` face saves three requests and ~145 kB of duplicate
transfer, and lets the browser interpolate between weights.

Run once, then commit ``web/src/styles/fonts.css`` and ``web/public/fonts/``.

    python scripts/fetch_fonts.py
"""

from __future__ import annotations

import hashlib
import pathlib
import re
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parents[1]
FONT_DIR = ROOT / "web" / "public" / "fonts"
CSS_OUT = ROOT / "web" / "src" / "styles" / "fonts.css"

CSS_URL = (
    "https://fonts.googleapis.com/css2?"
    "family=Instrument+Serif:ital@0;1"
    "&family=Inter:wght@300;400;500;600"
    "&family=JetBrains+Mono:wght@400;500"
    "&display=swap"
)

# A current Chrome UA is what makes Google serve woff2 instead of ttf.
UA = (
    "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 "
    "(KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36"
)

BLOCK = re.compile(
    r"/\*\s*(?P<subset>[\w-]+)\s*\*/\s*"
    r"@font-face\s*\{(?P<body>[^}]+)\}",
    re.S,
)
FACE = re.compile(r"font-family:\s*'(?P<family>[^']+)'")
STYLE = re.compile(r"font-style:\s*(?P<style>\w+)")
WEIGHT = re.compile(r"font-weight:\s*(?P<weight>\d+)")
SRC = re.compile(r"url\((?P<url>https://[^)]+\.woff2)\)")
RANGE = re.compile(r"unicode-range:\s*(?P<range>[^;]+);")


def slug(value: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", value.lower()).strip("-")


def fetch(url: str) -> bytes:
    request = urllib.request.Request(url, headers={"User-Agent": UA})
    with urllib.request.urlopen(request, timeout=60) as response:
        return response.read()


def main() -> None:
    css = fetch(CSS_URL).decode("utf-8")
    FONT_DIR.mkdir(parents=True, exist_ok=True)

    # family -> style -> {hash: {"weights": [...], "range": str, "bytes": b}}
    groups: dict[str, dict[str, dict[str, dict]]] = {}

    for match in BLOCK.finditer(css):
        if match.group("subset") != "latin":
            continue
        body = match.group("body")
        family = FACE.search(body)
        style = STYLE.search(body)
        weight = WEIGHT.search(body)
        src = SRC.search(body)
        span = RANGE.search(body)
        if not (family and style and weight and src and span):
            continue

        data = fetch(src.group("url"))
        digest = hashlib.sha256(data).hexdigest()
        entry = (
            groups.setdefault(family.group("family"), {})
            .setdefault(style.group("style"), {})
            .setdefault(digest, {"weights": [], "range": span.group("range").strip(), "data": data})
        )
        entry["weights"].append(int(weight.group("weight")))

    blocks: list[str] = []
    for family, styles in groups.items():
        for style, variants in styles.items():
            for digest, entry in variants.items():
                weights = sorted(entry["weights"])
                name = f"{slug(family)}-{style}.woff2"
                (FONT_DIR / name).write_bytes(entry["data"])

                if len(weights) > 1:
                    weight_rule = f"{weights[0]} {weights[-1]}"
                else:
                    weight_rule = str(weights[0])

                blocks.append(
                    "@font-face {\n"
                    f"  font-family: '{family}';\n"
                    f"  font-style: {style};\n"
                    f"  font-weight: {weight_rule};\n"
                    "  font-display: swap;\n"
                    f"  src: url('/fonts/{name}') format('woff2');\n"
                    f"  unicode-range: {entry['range']};\n"
                    "}\n"
                )
                print(
                    f"{name:34} weight {weight_rule:<9} "
                    f"{len(entry['data']):>7,} bytes  ({digest[:8]})"
                )

    header = (
        "/* Generated by scripts/fetch_fonts.py - do not edit by hand.\n"
        "   Latin subsets only, served from this origin. No third-party font\n"
        "   request, no render-blocking stylesheet from Google. */\n\n"
    )
    CSS_OUT.write_text(header + "\n".join(blocks), encoding="utf-8")

    total = sum(f.stat().st_size for f in FONT_DIR.glob("*.woff2"))
    print(f"\n{len(blocks)} faces, {total:,} bytes in {FONT_DIR.relative_to(ROOT)}")
    print(f"wrote {CSS_OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
